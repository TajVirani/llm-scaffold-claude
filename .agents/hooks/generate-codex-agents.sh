#!/usr/bin/env bash
# File: Generator (not a hook): build Codex custom-agent files from the scaffold's agent definitions.
# Usage:
#   generate-codex-agents.sh [--agents-dir DIR] [--out-dir DIR] [--check]
#     --agents-dir  source definitions (default: the agents/ folder next to this hooks folder, i.e. <project>/.agents/agents)
#     --out-dir     destination (default: <project>/.codex/agents, where <project> is the parent of .agents/)
#     --check       write nothing; exit 1 if any file would be created, changed or pruned (for tests and CI)
# Behaviour:
#   - One <out-dir>/<codex-name>.toml per <agents-dir>/*.md, in byte order (LC_ALL=C), with exactly three keys:
#       name                   = <codex-name>: frontmatter `name` (must equal the file basename) with every `-` mapped to `_`
#                                (fact-lookup -> fact_lookup). Codex 0.155.1 accepts only [a-z0-9_] in an agent_name (task_name); whether a
#                                hyphenated agent definition `name` loads is unverified, so the generator uses the safe form for both the
#                                key and the file name. Spawn with agent_type = <codex-name>; resolve-launch.sh still takes the definition
#                                name (--task-type fact-lookup). codex-pre-spawn.sh accepts both forms. Two definitions that map to the same
#                                <codex-name> are an input error.
#       description            = frontmatter `description`
#       developer_instructions = the body after the closing `---`, leading blank lines and trailing whitespace removed
#     Every other frontmatter key (tools, models, model, ...) is ignored. `model` is NEVER written: a toml `model` overrides the
#     spawn-time model on Codex 0.155.1, so writing one would defeat .workflow/agent-overrides.yaml. The orchestrator passes the
#     resolve-launch.sh model at spawn instead.
#   - developer_instructions is a TOML multi-line literal string ('''...''') when the body allows it (no ''' , no control
#     characters other than tab and newline), closed on its own line, so the value ends with one newline; otherwise a basic
#     string with JSON-compatible escapes (same value, also ending with one newline).
#   - Each file starts with a "# Generated by" marker line naming the source definition. A file in <out-dir> that carries the marker but has no source definition
#     is removed (pruned); files without the marker (user-written agents) are never touched.
#   - Deterministic: the same inputs give byte-identical output; unchanged files are not rewritten.
#   - All definitions are validated before anything is written: on any error nothing is written.
# Exit: 0 done (or --check clean); 1 --check found drift; 2 usage or input error (reason on stderr).
# Called by: install.sh after copying .agents/. Re-run on every install or upgrade.
# Sources: first-party; Codex custom-agent keys verified live on Codex 0.155.1;
#   prior art for md -> toml: EveryInc/compound-engineering-plugin src/converters/claude-to-codex.ts (MIT), github/spec-kit codex integration (MIT).
# Requires: bash 3.2+, jq, mikefarah yq v4, awk.

set -euo pipefail
export LC_ALL=C

MARKER="# Generated by .agents/hooks/generate-codex-agents.sh from .agents/agents/"

die() { echo "generate-codex-agents: $*" >&2; exit 2; }

here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
agents_dir=$here/../agents
out_dir=""
check=0
while [ $# -gt 0 ]; do
  case "$1" in
    --agents-dir) [ $# -ge 2 ] || die "--agents-dir needs a value"; agents_dir=$2; shift ;;
    --out-dir) [ $# -ge 2 ] || die "--out-dir needs a value"; out_dir=$2; shift ;;
    --check) check=1 ;;
    -h | --help) sed -n '/^# Usage:/,/^# Exit:/p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) die "unknown argument: $1" ;;
  esac
  shift
done

command -v jq >/dev/null 2>&1 || die "jq not found"
command -v yq >/dev/null 2>&1 || die "yq not found (mikefarah yq v4)"
case "$(yq --version 2>&1)" in *mikefarah*version\ v4.* | *mikefarah*version\ 4.*) ;; *) die "yq is not mikefarah yq v4" ;; esac

[ -d "$agents_dir" ] || die "agents dir not found: $agents_dir"
agents_dir=$(cd "$agents_dir" && pwd)
[ -n "$out_dir" ] || out_dir=$(cd "$here/../.." && pwd)/.codex/agents

tmp=$(mktemp -d "${TMPDIR:-/tmp}/gen-codex-agents.XXXXXX")
trap 'rm -rf "$tmp"' EXIT

# toml_basic: read stdin, print a TOML basic string (JSON string escapes are a subset TOML accepts).
toml_basic() { jq -Rs .; }

names=()
for src in "$agents_dir"/*.md; do
  [ -f "$src" ] || continue
  base=$(basename "$src" .md)
  [ "$(head -n 1 "$src")" = "---" ] || die "$src: no frontmatter (first line must be ---)"
  fm=$(yq --front-matter=extract -o=json -I=0 '.' "$src" 2>/dev/null) || die "$src: frontmatter is not valid YAML"
  jq -e 'type == "object"' <<<"$fm" >/dev/null || die "$src: frontmatter is not a mapping"
  name=$(jq -r '.name | if type == "string" then . else "" end' <<<"$fm")
  [ -n "$name" ] || die "$src: frontmatter name missing or not a string"
  [ "$name" = "$base" ] || die "$src: frontmatter name '$name' does not match the file name '$base'"
  grep -Eq '^[a-z0-9][a-z0-9_-]*$' <<<"$name" || die "$src: name '$name' must be lowercase letters, digits, - or _"
  jq -e '.description | type == "string" and (gsub("\\s"; "") != "")' <<<"$fm" >/dev/null || die "$src: frontmatter description missing, blank or not a string"
  cname=${name//-/_}
  case " ${names[*]-} " in *" $cname "*) die "$src: Codex name '$cname' (hyphens mapped to _) collides with another definition" ;; esac

  # Body: everything after the closing --- of the frontmatter; leading blank lines and trailing whitespace dropped.
  awk 'NR == 1 { next } !done && /^---[[:space:]]*$/ { done = 1; next } done { print }' "$src" \
    | awk 'started || NF { started = 1; print }' > "$tmp/body.raw"
  # Trim trailing whitespace at the end of the body (not per line).
  body=$(cat "$tmp/body.raw")
  body=${body%"${body##*[![:space:]]}"}
  [ -n "$body" ] || die "$src: body is empty (Codex requires non-blank developer_instructions)"
  printf '%s' "$body" > "$tmp/body"

  {
    printf '%s%s.md. Do not edit; re-run the generator (install.sh does).\n' "$MARKER" "$name"
    printf 'name = %s\n' "$(printf '%s' "$cname" | toml_basic)"
    printf 'description = %s\n' "$(jq -j '.description' <<<"$fm" | toml_basic)"
    if ! grep -q "'''" "$tmp/body" && ! LC_ALL=C grep -q "$(printf '[\001-\010\013-\037\177]')" "$tmp/body" ; then
      printf "developer_instructions = '''\n%s\n'''\n" "$body"
    else
      printf 'developer_instructions = %s\n' "$({ cat "$tmp/body"; echo; } | toml_basic)"
    fi
  } > "$tmp/$cname.toml"
  names+=("$cname")
done
[ "${#names[@]}" -gt 0 ] || die "no *.md definitions in $agents_dir"

# Plan: create/update, then prune marker-carrying files with no source.
drift=0
changes=()
for name in "${names[@]}"; do
  if [ ! -f "$out_dir/$name.toml" ]; then
    changes+=("create $name.toml")
  elif ! cmp -s "$tmp/$name.toml" "$out_dir/$name.toml"; then
    changes+=("update $name.toml")
  fi
done
prune=()
if [ -d "$out_dir" ]; then
  for f in "$out_dir"/*.toml; do
    [ -f "$f" ] || continue
    n=$(basename "$f" .toml)
    case " ${names[*]} " in *" $n "*) continue ;; esac
    grep -qF "$MARKER" <<<"$(head -n 1 "$f")" || continue
    prune+=("$f")
    changes+=("remove $n.toml")
  done
fi
[ "${#changes[@]}" -eq 0 ] || drift=1

if [ "$check" -eq 1 ]; then
  [ "$drift" -eq 0 ] && exit 0
  printf 'generate-codex-agents: out of date in %s:\n' "$out_dir" >&2
  printf '  %s\n' "${changes[@]}" >&2
  exit 1
fi

mkdir -p "$out_dir"
for name in "${names[@]}"; do
  cmp -s "$tmp/$name.toml" "$out_dir/$name.toml" 2>/dev/null || cp "$tmp/$name.toml" "$out_dir/$name.toml"
done
for f in ${prune[@]+"${prune[@]}"}; do rm -f "$f"; done
exit 0
